# ── Repeated Training Without FK Violations ───────────────────────


def test_repeated_training_no_fk_violations(store: DuckDBStore) -> None:
    """
    Integration test: simulate two full training cycles.
    Each cycle:
      1. Begin transaction
      2. Delete derived tables
      3. Re-add intents (same names → same IDs)
      4. Re-add examples
      5. Commit

    Must not raise IntegrityError / ForeignKeyViolation.
    """
    intent_names = ["greeting", "weather_query", "time_query"]

    # ── Cycle 1 ──────────────────────────────────────────────
    store.begin_transaction()
    store.delete_derived_tables()
    for name in intent_names:
        intent_id = store.add_intent(name)
        store.add_example(intent_id, f"{name} example 1")
        store.add_example(intent_id, f"{name} example 2")
    store.commit()

    # Verify cycle 1 data
    intents = store.get_intents()
    assert len(intents) >= len(intent_names)

    # ── Cycle 2 ──────────────────────────────────────────────
    store.begin_transaction()
    store.delete_derived_tables()
    for name in intent_names:
        intent_id = store.add_intent(name)
        store.add_example(intent_id, f"{name} new example 1")
        store.add_example(intent_id, f"{name} new example 2")
    store.commit()

    # Verify cycle 2: examples should be the new ones
    for name in intent_names:
        intents_list = store.get_intents()
        match = [i for i in intents_list if i["name"] == name]
        assert len(match) == 1
        examples = store.get_examples(match[0]["id"])
        assert len(examples) == 2
        assert all("new example" in e["text"] for e in examples)


def test_repeated_training_preserves_intent_ids(store: DuckDBStore) -> None:
    """
    Verify that across multiple training cycles, intent IDs remain stable.
    This is critical for referential integrity with other tables.
    """
    intent_names = ["brightness_up", "brightness_down", "volume_up"]

    # Cycle 1
    ids_cycle_1 = {}
    store.begin_transaction()
    store.delete_derived_tables()
    for name in intent_names:
        ids_cycle_1[name] = store.add_intent(name)
        store.add_example(ids_cycle_1[name], f"{name} ex1")
    store.commit()

    # Cycle 2
    ids_cycle_2 = {}
    store.begin_transaction()
    store.delete_derived_tables()
    for name in intent_names:
        ids_cycle_2[name] = store.add_intent(name)
        store.add_example(ids_cycle_2[name], f"{name} ex2")
    store.commit()

    # Cycle 3
    ids_cycle_3 = {}
    store.begin_transaction()
    store.delete_derived_tables()
    for name in intent_names:
        ids_cycle_3[name] = store.add_intent(name)
        store.add_example(ids_cycle_3[name], f"{name} ex3")
    store.commit()

    for name in intent_names:
        assert ids_cycle_1[name] == ids_cycle_2[name] == ids_cycle_3[name], (
            f"Intent '{name}' ID changed across training cycles: "
            f"{ids_cycle_1[name]} → {ids_cycle_2[name]} → {ids_cycle_3[name]}"
        )


# ── Migration Logic ───────────────────────────────────────────────


def test_migration_creates_derived_tables(monkeypatch) -> None:
    """
    Simulate a fresh database that only has schema version 1 tables.
    Verify that initialize() runs migration to add intent_embeddings
    and cached_embeddings.
    """
    import tempfile
    import os

    with tempfile.NamedTemporaryFile(suffix=".duckdb", delete=False) as f:
        db_path = f.name
    os.unlink(db_path)

    # Create a store with schema version 1 only (no derived tables)
    s = DuckDBStore(db_path=db_path)
    conn = s._get_conn()

    # Manually create only v1 tables (no intent_embeddings / cached_embeddings)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS intents (
            id INTEGER PRIMARY KEY,
            name VARCHAR NOT NULL UNIQUE,
            description VARCHAR,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS intent_examples (
            id INTEGER PRIMARY KEY,
            intent_id INTEGER,
            text VARCHAR NOT NULL,
            embedding FLOAT[],
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (intent_id) REFERENCES intents(id)
        )
    """)
    conn.execute("""
        CREATE TABLE IF NOT EXISTS schema_version (
            version INTEGER PRIMARY KEY,
            applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    conn.execute("INSERT INTO schema_version (version) VALUES (1)")

    # Now run initialize() — should detect version 1 and migrate to version 2
    s.initialize()

    # Verify derived tables exist
    tables = conn.execute(
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema = 'main'"
    ).fetchall()
    table_names = {t[0] for t in tables}
    assert "intent_embeddings" in table_names, (
        "Migration should create intent_embeddings table"
    )
    assert "cached_embeddings" in table_names, (
        "Migration should create cached_embeddings table"
    )

    # Verify schema version was updated
    current_version = conn.execute(
        "SELECT COALESCE(MAX(version), 0) FROM schema_version"
    ).fetchone()[0]
    assert current_version >= 2, (
        f"Schema version should be >= 2 after migration, got {current_version}"
    )

    s.close()
    os.unlink(db_path)


# ── Audit: No DELETE on intents table ─────────────────────────────


def test_no_delete_statements_on_intents() -> None:
    """
    Audit: verify that the source code contains no DELETE statements
    targeting the intents table.  This is a static analysis check.
    """
    import pathlib
    store_path = pathlib.Path("memory/duckdb_store.py")
    content = store_path.read_text()
    # Look for any DELETE that mentions "intents" (case-insensitive)
    lines = content.splitlines()
    for i, line in enumerate(lines, 1):
        stripped = line.strip().upper()
        if "DELETE" in stripped and "INTENTS" in stripped:
            # Allow DELETE FROM intent_embeddings or intent_examples
            # but NOT DELETE FROM intents
            if "DELETE FROM INTENTS" in stripped.replace("_", " ").split():
                pytest.fail(
                    f"Line {i}: DELETE statement targets intents table: {line}"
                )
