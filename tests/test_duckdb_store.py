"""
Integration tests for DuckDBStore using native DuckDB APIs.

Tests verify:
- Table creation with GENERATED BY DEFAULT AS IDENTITY
- INSERT ... RETURNING id returns correct auto-generated IDs
- ON CONFLICT (upsert) behavior
- All CRUD operations return expected types and values
"""

import os
import tempfile
from pathlib import Path
from typing import Generator

import numpy as np
import pytest

from memory.duckdb_store import DuckDBStore


@pytest.fixture
def store() -> Generator[DuckDBStore, None, None]:
    """Create a fresh DuckDBStore backed by a temporary file for each test."""
    with tempfile.NamedTemporaryFile(suffix=".duckdb", delete=False) as f:
        db_path = f.name
    # DuckDB requires the file to either not exist or be a valid database;
    # NamedTemporaryFile creates a 0-byte file, so remove it first.
    os.unlink(db_path)
    _store = DuckDBStore(db_path=db_path)
    _store.initialize()
    yield _store
    _store.close()
    os.unlink(db_path)


